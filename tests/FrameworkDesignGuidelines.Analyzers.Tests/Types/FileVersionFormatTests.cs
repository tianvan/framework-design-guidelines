using Verifier = FrameworkDesignGuidelines.Analyzers.Tests.Verifiers.AnalyzerVerifier<
    FrameworkDesignGuidelines.Analyzers.Types.FileVersionFormatAnalyzer>;

namespace FrameworkDesignGuidelines.Analyzers.Tests.Types;

public sealed class FileVersionFormatTests
{
    [Fact]
    public Task File_version_with_four_numbers_is_not_reported()
    {
        return Verifier.VerifyAsync(
            """
            using System.Reflection;

            [assembly: AssemblyFileVersion("3.5.21022.8")]
            [assembly: AssemblyVersion("3.5")]
            """);
    }

    [Fact]
    public Task File_version_with_another_format_is_reported()
    {
        return Verifier.VerifyAsync(
            """
            using System.Reflection;

            [assembly: {|FDG4062:AssemblyFileVersion("3.5")|}]
            """);
    }

    [Fact]
    public Task File_version_from_a_constant_is_checked()
    {
        return Verifier.VerifyAsync(
            """
            using System.Reflection;

            [assembly: {|FDG4062:System.Reflection.AssemblyFileVersion(Versions.File)|}]

            internal static class Versions
            {
                public const string File = "1.0.0-beta";
            }
            """);
    }

    [Fact]
    public Task Generated_file_version_is_not_reported()
    {
        return Verifier.VerifyAsync(
            "public class C { }",
            ("/0/obj/Sample.AssemblyInfo.cs",
                """
                // <auto-generated/>
                [assembly: System.Reflection.AssemblyFileVersion("1.0")]
                """));
    }
}
